import { Injectable } from "@nestjs/common";
import { INodeDefination, INodeProperty } from "../interfaces/node-registry.interface";
import { Node } from "../decorators/node.decorator";
import { ChatGoogleGenerativeAI } from "@langchain/google-genai"
import {ChatOpenAI} from "@langchain/openai"
import {ChatAnthropic} from "@langchain/anthropic"
import { AiProviderRegistry } from "./AiProviderRegistry";
import { HumanMessage, SystemMessage } from "@langchain/core/messages";


const PROVIDER_MAP = {
    Google:{Cls:ChatGoogleGenerativeAI},
    OpenAI:{Cls:ChatOpenAI},
    Anthropic:{Cls:ChatAnthropic}

}

@Injectable()
@Node()
export class AiAgentNode implements INodeDefination {

    constructor(
        private readonly aiProvider:AiProviderRegistry
    ){}
    name = "AI Agent";
    type = "aiAgent";
    description = "Process text or data using an LLM with custom system instructions";
    icon = "Bot";
    inputs = 1;
    outputs = 1;

    properties: INodeProperty[] = [
        {
            displayName: "Model Provider",
            name: "provider",
            type: "options",
            options: ["Google", "OpenAI", "Anthropic"],
            default: "Google Gemini"
        },
        {
            displayName: "Model Name",
            name: "modelName",
            type: "options",
            options: ["gemini-2.5-flash", "gemini-2.5-pro", "gpt-4o", "claude-3-5-sonnet"],
            default: "gemini-2.5-flash"
        },
        {
            displayName: "API Keys",
            name: "apiKeys",
            type: "string",
            placeholder:"sk.......",
            default:""
        },
        {
            displayName: "System Prompt",
            name: "systemPrompt",
            type: "string",
            placeholder: "You are a helpful data extraction assistant...",
            default: "You are a helpful assistant."
        },
        {
            displayName: "User Prompt",
            name: "userPrompt",
            type: "string",
            placeholder: "Write an email...",
            default: ""
        },
        {
            displayName: "Temperature",
            name: "temperature",
            type: "number",
            placeholder: "0.7",
            default: 0.7
        },
        {
            displayName: "Enable JSON Mode",
            name: "jsonMode",
            type: "boolean",
            default: false
        }
    ];
    async execute(nodeParameters: any, incomingData: any[]) {
        const { provider, modelName, systemPrompt, temperature, jsonMode, apiKeys, userPrompt } = nodeParameters;
        
        const chatModel = this.aiProvider.getModel(provider, modelName, apiKeys, temperature);

        const needJsonData = jsonMode;
        const customSysPrompt = needJsonData 
            ? `You are a helpful AI assistant and based on the user question you always have to return in JSON format. \n ${systemPrompt}` 
            : systemPrompt;

        const messages = [
            new SystemMessage(customSysPrompt),
            new HumanMessage(userPrompt)
        ];

        const res = await chatModel.invoke(messages);

        // Return clean standardized node output as an array
        return {
            data: [
                {
                    output: res.content, // The actual text generated by the LLM
                    rawInput: incomingData
                }
            ]
        };
    }
}